#!/usr/bin/env python3
"""
CocoCare Stage 4 — baseline ML analysis
======================================

Input default:
  ml/data/coconut_health/stage4/data/cococare_stage4_outputs/
      stage4_combined_scenarios.csv

Default outputs are written beside this script:
  stage4_ml_baseline_outputs/{tables,figures,models,reports}

Targets:
  current_day: weather/scenario inputs on day t -> day-t simulated stress label
  next_day:    weather/scenario inputs on day t -> day-(t+1) simulated stress label

Evaluation:
  * Date-grouped random 70/15/15 exploratory split.
  * All scenarios for a target date stay in the same partition.
  * Model selection uses validation macro-F1 (balanced accuracy tie-break).
  * Selected model is refit on train+validation and evaluated once on test.
  * Chronological weather-baseline diagnostic is reported separately.
  * Validation permutation importance is calculated using the train-fitted model.

Scientific interpretation:
  The target is rule-derived by the same provisional water-balance simulator.
  Results measure reproduction of simulated labels, not observed palm stress,
  field efficacy, irrigation savings, or agronomic validity.

Feature groups:
  A weather_baseline: weather + ET0 + potential ETc
  B scenario_aware: A + scenario identity
  C intervention_aware: B + day-t simulated irrigation litres

C is exploratory only. Irrigation volume is generated by the same simulator,
and for a real-time forecast it may not yet be known at prediction time.
"""

from __future__ import annotations
import argparse
import json
import warnings
from pathlib import Path

import joblib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from sklearn.base import clone
from sklearn.compose import ColumnTransformer
from sklearn.dummy import DummyClassifier
from sklearn.ensemble import ExtraTreesClassifier, RandomForestClassifier, GradientBoostingClassifier
from sklearn.impute import SimpleImputer
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score, balanced_accuracy_score, classification_report,
    confusion_matrix, ConfusionMatrixDisplay, f1_score, precision_score,
    recall_score,
)
from sklearn.model_selection import GroupShuffleSplit
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.svm import SVC
from sklearn.tree import DecisionTreeClassifier

SEED = 42
DATE = "date"
SCENARIO = "scenario"
TARGET = "water_stress_rule_derived"
CLASSES = ["low", "moderate", "high"]
EXPECTED_SCENARIOS = {"stage4_weather_only", "stage4_model_triggered_irrigation"}

WEATHER = [
    "rainfall_mm", "tmax_c", "tmin_c", "solar_radiation_mj_m2_day",
    "relative_humidity_pct", "wind_speed_m_s", "et0_mm_day",
    "etc_potential_mm_day_modelled",
]
IRRIGATION = "irrigation_litres_per_palm_simulated"

FEATURE_GROUPS = {
    "weather_baseline": {"numeric": WEATHER, "categorical": []},
    "scenario_aware": {"numeric": WEATHER, "categorical": [SCENARIO]},
    "intervention_aware": {"numeric": WEATHER + [IRRIGATION], "categorical": [SCENARIO]},
}

EXCLUDED = {
    "effective_rainfall_mm_modelled": "Water-balance intermediate",
    "runoff_mm_modelled": "Water-balance intermediate",
    "irrigation_mm_simulated": "Duplicate transformation of irrigation litres using assumed wetted area",
    "actual_et_mm_day_modelled": "Downstream water-balance output",
    "drainage_mm_modelled": "Downstream water-balance output",
    "soil_water_storage_mm_modelled": "Direct simulated state used to derive stress",
    "depletion_fraction_modelled": "Direct variable used to derive stress label",
    "depletion_before_irrigation_fraction_modelled": "Direct trigger variable used by irrigation policy",
    "soil_moisture_vwc_pct_simulated": "Simulated state derived from storage",
    "recommended_action_simulated": "Action derived from stress label",
    TARGET: "Prediction target; never an input",
    "soil_temperature_c": "Intentionally unmodelled; all missing",
    "simulated_palm_age_months": "Constant assessment metadata; no age variation",
    "weather_source": "Source metadata",
    "weather_source_url": "Source metadata",
    "soil_temperature_status": "Status metadata",
    "model_status": "Status metadata",
    "stress_label_status": "Status metadata",
    "age_parameter_status": "Status metadata",
    "effective_wetted_area_m2_assumed": "Constant model assumption",
}

def arguments():
    script_dir = Path(__file__).resolve().parent
    roots = [script_dir, *script_dir.parents]
    repo = next((p for p in roots if (p / "ml").is_dir()), script_dir)
    default_data = repo / "ml/data/coconut_health/stage4/data/cococare_stage4_outputs/stage4_combined_scenarios.csv"
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", default=str(default_data), help="Combined Stage 4 CSV")
    ap.add_argument("--output", default=str(script_dir / "stage4_ml_baseline_outputs"))
    ap.add_argument("--permutation-repeats", type=int, default=10)
    return ap.parse_args()

def make_dirs(root):
    root.mkdir(parents=True, exist_ok=True)
    dirs = {"root": root}
    for n in ("tables", "figures", "models", "reports"):
        dirs[n] = root / n
        dirs[n].mkdir(parents=True, exist_ok=True)
    return dirs

def load_data(path):
    if not path.exists():
        raise FileNotFoundError(f"Dataset not found: {path}\nUse --data to specify the combined CSV.")
    df = pd.read_csv(path)
    required = [DATE, SCENARIO, TARGET, *WEATHER, IRRIGATION]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")
    df[DATE] = pd.to_datetime(df[DATE], errors="coerce").dt.normalize()
    if df[DATE].isna().any():
        raise ValueError("Invalid dates found.")
    df = df.sort_values([SCENARIO, DATE]).reset_index(drop=True)
    if df.duplicated([DATE, SCENARIO]).any():
        raise ValueError("Duplicate date-scenario rows found.")
    if set(df[SCENARIO].unique()) != EXPECTED_SCENARIOS:
        raise ValueError(f"Expected scenarios {sorted(EXPECTED_SCENARIOS)}, found {sorted(df[SCENARIO].unique())}")
    per_date = df.groupby(DATE)[SCENARIO].nunique()
    if not (per_date == 2).all():
        raise ValueError("Every date must contain both Stage 4 scenarios.")
    for scenario, part in df.groupby(SCENARIO):
        dates = part[DATE].sort_values()
        if not (dates.diff().dropna() == pd.Timedelta(days=1)).all():
            raise ValueError(f"Dates are not consecutive in {scenario}; next-day alignment unsafe.")
    for col in WEATHER:
        wide = df.pivot(index=DATE, columns=SCENARIO, values=col)
        vals = wide[sorted(EXPECTED_SCENARIOS)].to_numpy(dtype=float)
        if not np.allclose(vals[:, 0], vals[:, 1], equal_nan=True):
            raise ValueError(f"Weather differs between scenarios for {col}.")
    for col in WEATHER + [IRRIGATION]:
        df[col] = pd.to_numeric(df[col], errors="coerce")
    if df[WEATHER + [IRRIGATION, TARGET]].isna().any().any():
        raise ValueError("Missing values in required model columns.")
    unexpected = set(df[TARGET].astype(str).unique()) - set(CLASSES)
    if unexpected:
        raise ValueError(f"Unexpected target labels: {unexpected}")
    return df

def objectives(df):
    x = df.sort_values([SCENARIO, DATE]).copy()
    x["target_current"] = x[TARGET]
    x["target_date_current"] = x[DATE]
    grp = x.groupby(SCENARIO, sort=False)
    x["target_next"] = grp[TARGET].shift(-1)
    x["target_date_next"] = grp[DATE].shift(-1)
    valid = x["target_date_next"].notna()
    if not ((x.loc[valid, "target_date_next"] - x.loc[valid, DATE]) == pd.Timedelta(days=1)).all():
        raise ValueError("Next-day labels are not exactly one day ahead.")
    return {
        "current_day": (x.copy(), "target_current", "target_date_current"),
        "next_day": (x.loc[valid].copy(), "target_next", "target_date_next"),
    }

def random_split(df, group_col):
    df = df.reset_index(drop=True)
    i_train, i_tmp = next(GroupShuffleSplit(n_splits=1, test_size=.30, random_state=SEED).split(df, groups=df[group_col]))
    train, tmp = df.iloc[i_train].copy(), df.iloc[i_tmp].copy()
    i_val, i_test = next(GroupShuffleSplit(n_splits=1, test_size=.50, random_state=SEED+1).split(tmp, groups=tmp[group_col]))
    return train, tmp.iloc[i_val].copy(), tmp.iloc[i_test].copy()

def chronological_split(df, group_col):
    dates = np.sort(df[group_col].unique())
    n = len(dates)
    a, b = int(.70*n), int(.85*n)
    d_train, d_val, d_test = set(dates[:a]), set(dates[a:b]), set(dates[b:])
    return tuple(df[df[group_col].isin(ds)].copy() for ds in (d_train, d_val, d_test))

def check_splits(parts, group_col):
    sets = [set(p[group_col].unique()) for p in parts]
    if any(sets[i] & sets[j] for i in range(3) for j in range(i+1, 3)):
        raise AssertionError("Date overlap across partitions.")
    for p in parts:
        if not (p.groupby(group_col)[SCENARIO].nunique() == 2).all():
            raise AssertionError("Scenario pair split across partitions.")

def preprocessor(numeric, categorical, scale):
    nsteps = [("imputer", SimpleImputer(strategy="median"))]
    if scale:
        nsteps.append(("scaler", StandardScaler()))
    transformers = [("num", Pipeline(nsteps), numeric)]
    if categorical:
        transformers.append(("cat", Pipeline([
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore")),
        ]), categorical))
    return ColumnTransformer(transformers, remainder="drop")

def model_zoo(numeric, categorical):
    def pipe(est, scale=False):
        return Pipeline([("prep", preprocessor(numeric, categorical, scale)), ("model", est)])
    return {
        "Dummy_MostFrequent": pipe(DummyClassifier(strategy="most_frequent")),
        "LogisticRegression": pipe(LogisticRegression(max_iter=3000, class_weight="balanced", random_state=SEED), True),
        "DecisionTree": pipe(DecisionTreeClassifier(class_weight="balanced", min_samples_leaf=5, random_state=SEED)),
        "RandomForest": pipe(RandomForestClassifier(n_estimators=400, class_weight="balanced", min_samples_leaf=2, max_features="sqrt", n_jobs=-1, random_state=SEED)),
        "ExtraTrees": pipe(ExtraTreesClassifier(n_estimators=400, class_weight="balanced", min_samples_leaf=2, max_features="sqrt", n_jobs=-1, random_state=SEED)),
        "SVM_RBF": pipe(SVC(kernel="rbf", C=1.0, class_weight="balanced"), True),
        "GradientBoosting": pipe(GradientBoostingClassifier(random_state=SEED)),
    }

def score_metrics(y, pred):
    return {
        "records": int(len(y)),
        "accuracy": float(accuracy_score(y, pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y, pred)),
        "macro_precision": float(precision_score(y, pred, labels=CLASSES, average="macro", zero_division=0)),
        "macro_recall": float(recall_score(y, pred, labels=CLASSES, average="macro", zero_division=0)),
        "macro_f1": float(f1_score(y, pred, labels=CLASSES, average="macro", zero_division=0)),
        "weighted_f1": float(f1_score(y, pred, average="weighted", zero_division=0)),
    }

def coverage(y):
    present = set(pd.Series(y).dropna().unique())
    return {
        "present_classes": "|".join(c for c in CLASSES if c in present),
        "missing_classes": "|".join(c for c in CLASSES if c not in present),
    }

def save_split_table(parts, target, group_col, objective, track, path):
    rows = []
    for name, p in zip(("train", "validation", "test"), parts):
        counts = p[target].value_counts().reindex(CLASSES, fill_value=0)
        rows.append({
            "objective": objective, "track": track, "split": name,
            "records": len(p), "unique_target_dates": p[group_col].nunique(),
            "first_target_date": str(p[group_col].min().date()),
            "last_target_date": str(p[group_col].max().date()),
            **coverage(p[target]),
            **{f"class_{c}": int(counts[c]) for c in CLASSES},
        })
    pd.DataFrame(rows).to_csv(path, index=False)

def save_distribution(parts, target, path, title):
    counts = pd.DataFrame({
        n: p[target].value_counts().reindex(CLASSES, fill_value=0)
        for n, p in zip(("Train", "Validation", "Test"), parts)
    }).T
    counts.to_csv(path.with_suffix(".csv"))
    ax = counts.plot(kind="bar", figsize=(8, 5))
    ax.set(title=title, xlabel="Partition", ylabel="Records")
    ax.grid(axis="y", alpha=.25)
    plt.xticks(rotation=0)
    plt.tight_layout()
    plt.savefig(path, dpi=220, bbox_inches="tight")
    plt.close()

def save_cm(y, pred, path, title):
    cm = confusion_matrix(y, pred, labels=CLASSES)
    fig, ax = plt.subplots(figsize=(6, 5))
    ConfusionMatrixDisplay(cm, display_labels=CLASSES).plot(ax=ax, cmap="Blues", colorbar=False, values_format="d")
    ax.set_title(title)
    fig.tight_layout()
    fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)

def run_random(objective, data, target, group_col, dirs, repeats):
    parts = random_split(data, group_col)
    train, val, test = parts
    check_splits(parts, group_col)
    save_split_table(parts, target, group_col, objective, "date_grouped_random",
                     dirs["tables"] / f"{objective}_random_split_diagnostics.csv")
    save_distribution(parts, target, dirs["figures"] / f"{objective}_random_class_distribution.png",
                      f"{objective}: date-grouped random split")

    comparisons, selected = [], []
    for group_name, spec in FEATURE_GROUPS.items():
        numeric, categorical = spec["numeric"], spec["categorical"]
        features = numeric + categorical
        candidates = []
        for model_name, template in model_zoo(numeric, categorical).items():
            fitted = clone(template).fit(train[features], train[target])
            pred = fitted.predict(val[features])
            m = score_metrics(val[target], pred)
            comparisons.append({
                "objective": objective, "feature_group": group_name,
                "model": model_name, **{f"validation_{k}": v for k, v in m.items()},
                **{f"validation_{k}": v for k, v in coverage(val[target]).items()},
                "features": "|".join(features),
            })
            candidates.append((model_name, template, fitted, m))
        best_name, best_template, best_val_model, best_metrics = max(
            candidates, key=lambda z: (z[3]["macro_f1"], z[3]["balanced_accuracy"])
        )

        # Permutation importance uses the model trained only on train, evaluated on validation.
        prefix = f"{objective}_random_{group_name}_{best_name}"
        if repeats > 0:
            try:
                perm = permutation_importance(
                    best_val_model, val[features], val[target],
                    scoring="f1_macro", n_repeats=repeats, random_state=SEED, n_jobs=-1
                )
                imp = pd.DataFrame({
                    "feature": features,
                    "importance_mean": perm.importances_mean,
                    "importance_std": perm.importances_std,
                }).sort_values("importance_mean", ascending=False)
                imp.to_csv(dirs["tables"] / f"{prefix}_validation_permutation_importance.csv", index=False)
                top = imp.head(15).sort_values("importance_mean")
                fig, ax = plt.subplots(figsize=(9, 5.5))
                ax.barh(top.feature, top.importance_mean, xerr=top.importance_std)
                ax.set_xlabel("Decrease in validation macro-F1 after permutation")
                ax.set_title(f"{prefix}: validation permutation importance")
                ax.grid(axis="x", alpha=.25)
                fig.tight_layout()
                fig.savefig(dirs["figures"] / f"{prefix}_validation_permutation_importance.png", dpi=220, bbox_inches="tight")
                plt.close(fig)
            except Exception as exc:
                (dirs["reports"] / f"{prefix}_permutation_warning.txt").write_text(str(exc), encoding="utf-8")

        train_val = pd.concat([train, val]).sort_values(group_col)
        final_model = clone(best_template).fit(train_val[features], train_val[target])
        test_pred = final_model.predict(test[features])
        test_m = score_metrics(test[target], test_pred)
        save_cm(test[target], test_pred, dirs["figures"] / f"{prefix}_test_confusion_matrix.png",
                f"{prefix}: held-out test")
        report = classification_report(test[target], test_pred, labels=CLASSES, output_dict=True, zero_division=0)
        pd.DataFrame(report).T.to_csv(dirs["reports"] / f"{prefix}_test_classification_report.csv")
        joblib.dump({
            "model": final_model, "model_name": best_name, "features": features,
            "objective": objective, "feature_group": group_name, "classes": CLASSES,
            "selected_by": "validation_macro_f1_then_balanced_accuracy",
            "validation_metrics": best_metrics, "random_state": SEED,
            "target_warning": "Rule-derived simulated target, not field ground truth.",
        }, dirs["models"] / f"{prefix}.joblib")
        selected.append({
            "objective": objective, "feature_group": group_name,
            "selected_model": best_name,
            "selection_metric": "validation_macro_f1",
            "validation_macro_f1": best_metrics["macro_f1"],
            "validation_balanced_accuracy": best_metrics["balanced_accuracy"],
            **{f"test_{k}": v for k, v in test_m.items()},
            **{f"test_{k}": v for k, v in coverage(test[target]).items()},
        })
    pd.DataFrame(comparisons).to_csv(dirs["tables"] / f"{objective}_random_validation_model_comparison.csv", index=False)
    pd.DataFrame(selected).to_csv(dirs["tables"] / f"{objective}_random_selected_test_results.csv", index=False)
    return comparisons, selected

def run_chronological(objective, data, target, group_col, dirs):
    parts = chronological_split(data, group_col)
    check_splits(parts, group_col)
    save_split_table(parts, target, group_col, objective, "chronological_diagnostic",
                     dirs["tables"] / f"{objective}_chronological_split_diagnostics.csv")
    save_distribution(parts, target, dirs["figures"] / f"{objective}_chronological_class_distribution.png",
                      f"{objective}: chronological diagnostic")
    train, val, test = parts
    rows = []
    # Fixed reference models only; no tuning/selection from the chronological validation window.
    templates = model_zoo(WEATHER, [])
    for model_name in ("Dummy_MostFrequent", "RandomForest"):
        model = clone(templates[model_name]).fit(train[WEATHER], train[target])
        for split_name, part in (("validation", val), ("test", test)):
            pred = model.predict(part[WEATHER])
            rows.append({
                "objective": objective, "model": model_name, "split": split_name,
                **coverage(part[target]), **score_metrics(part[target], pred),
            })
            if split_name == "test":
                save_cm(part[target], pred, dirs["figures"] / f"{objective}_chronological_{model_name}_test_cm.png",
                        f"{objective}: chronological {model_name} test")
    pd.DataFrame(rows).to_csv(dirs["tables"] / f"{objective}_chronological_diagnostic_metrics.csv", index=False)
    return rows

def main():
    args = arguments()
    data_path = Path(args.data).expanduser().resolve()
    output = Path(args.output).expanduser().resolve()
    dirs = make_dirs(output)
    print("="*72, "\nCOCOCARE STAGE 4 — BASELINE ML\n", "="*72, sep="")
    print("Input:", data_path)
    df = load_data(data_path)
    print(f"Validated {len(df)} rows, {df[DATE].nunique()} dates, {len(df.columns)} columns")
    print("Scenario rows:\n", df[SCENARIO].value_counts().to_string())
    print("Target by scenario:\n", pd.crosstab(df[SCENARIO], df[TARGET]).to_string())

    audit = {
        "input": str(data_path), "rows": int(len(df)), "columns": int(len(df.columns)),
        "unique_dates": int(df[DATE].nunique()), "date_start": str(df[DATE].min().date()),
        "date_end": str(df[DATE].max().date()),
        "scenario_counts": {str(k): int(v) for k,v in df[SCENARIO].value_counts().items()},
        "target_counts_by_scenario": {
            str(s): {str(k): int(v) for k,v in p[TARGET].value_counts().items()}
            for s,p in df.groupby(SCENARIO)
        },
        "missing_values": {str(k): int(v) for k,v in df.isna().sum().items() if v},
        "interpretation": "Rule-derived simulation target; not measured field stress.",
    }
    (dirs["reports"] / "dataset_audit.json").write_text(json.dumps(audit, indent=2), encoding="utf-8")
    (dirs["reports"] / "excluded_features_and_reasons.json").write_text(json.dumps(EXCLUDED, indent=2), encoding="utf-8")
    manifest = []
    for name, spec in FEATURE_GROUPS.items():
        for f in spec["numeric"]:
            manifest.append({"feature_group": name, "feature": f, "type": "numeric",
                             "note": "day-t weather input" if f != IRRIGATION else "day-t simulated irrigation; exploratory and potentially unavailable at forecast time"})
        for f in spec["categorical"]:
            manifest.append({"feature_group": name, "feature": f, "type": "one-hot categorical",
                             "note": "simulation scenario identity"})
    pd.DataFrame(manifest).to_csv(dirs["tables"] / "feature_manifest.csv", index=False)

    all_comp, all_selected, all_chrono = [], [], []
    for objective, (data, target, target_date) in objectives(df).items():
        print(f"\n{objective}: {len(data)} rows; target classes:")
        print(data[target].value_counts().reindex(CLASSES, fill_value=0).to_string())
        comp, selected = run_random(objective, data, target, target_date, dirs, max(0, args.permutation_repeats))
        chrono = run_chronological(objective, data, target, target_date, dirs)
        all_comp.extend(comp); all_selected.extend(selected); all_chrono.extend(chrono)

    pd.DataFrame(all_comp).to_csv(dirs["tables"] / "all_random_validation_model_comparisons.csv", index=False)
    pd.DataFrame(all_selected).to_csv(dirs["tables"] / "all_random_selected_test_results.csv", index=False)
    pd.DataFrame(all_chrono).to_csv(dirs["tables"] / "all_chronological_diagnostic_metrics.csv", index=False)
    meta = {
        "project": "CocoCare", "stage": "Stage 4", "input": str(data_path),
        "output": str(output), "random_state": SEED,
        "split": "Date-grouped random 70/15/15; both scenario rows for each target date remain together.",
        "selection": "Validation macro-F1, balanced accuracy tie-break; test evaluated after selection.",
        "objectives": ["current_day", "next_day"],
        "feature_groups": FEATURE_GROUPS,
        "target_caveat": "Target is rule-derived by the Stage 4 simulator, not field-observed ground truth.",
        "intervention_caveat": "Irrigation litres are generated by the same simulation and may not be known at forecast time.",
        "chronological_track": "Separate diagnostic with fixed weather-only Dummy and Random Forest; not used for model selection.",
        "permutation_importance": "Computed on validation using the model fitted on training data only.",
    }
    (dirs["reports"] / "experiment_metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print("\nFinished. Output directory:", output)
    print("Main comparison:", dirs["tables"] / "all_random_validation_model_comparisons.csv")
    print("Selected test results:", dirs["tables"] / "all_random_selected_test_results.csv")
    print("Reminder: simulated-label reproduction is not field validation.")

if __name__ == "__main__":
    warnings.filterwarnings("ignore", category=FutureWarning)
    main()
