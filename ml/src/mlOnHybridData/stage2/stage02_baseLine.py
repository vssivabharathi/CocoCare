def load_and_validate(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Dataset not found: {path}\n"
            "Pass the correct location using --data."
        )

    df = pd.read_csv(path)
    required = [
        DATE_COL, SCENARIO_COL, TARGET_SOURCE,
        *WEATHER_FEATURES, IRRIGATION_FEATURE,
    ]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Required columns missing from dataset: {missing}")

    df[DATE_COL] = pd.to_datetime(df[DATE_COL], errors="raise")
    df = df.sort_values([SCENARIO_COL, DATE_COL]).reset_index(drop=True)

    if df.duplicated([DATE_COL, SCENARIO_COL]).any():
        raise ValueError("Duplicate date-scenario records found.")

    scenarios = set(df[SCENARIO_COL].dropna().unique())
    expected_scenarios = {"weather_only", "tnau_guided_irrigation"}
    if scenarios != expected_scenarios:
        raise ValueError(
            f"Expected scenarios {sorted(expected_scenarios)}, found {sorted(scenarios)}. "
            "Update the experiment design if the scenario set has changed."
        )

    # Each date should have exactly one row from each scenario.
    scenario_counts = df.groupby(DATE_COL)[SCENARIO_COL].nunique()
    if not (scenario_counts == 2).all():
        raise ValueError("Every date must contain both scenario records.")

    # Weather should be identical for the paired scenarios on a given date.
    for col in WEATHER_FEATURES:
        wide = df.pivot(index=DATE_COL, columns=SCENARIO_COL, values=col)
        if not np.allclose(
            wide["weather_only"].to_numpy(),
            wide["tnau_guided_irrigation"].to_numpy(),
            equal_nan=True,
        ):
            raise ValueError(f"Weather feature differs between scenarios: {col}")

    if not set(df[TARGET_SOURCE].dropna().unique()).issubset(set(CLASSES)):
        raise ValueError("Unexpected target labels found.")

    # The source data should have consecutive daily observations per scenario.
    for scenario, part in df.groupby(SCENARIO_COL):
        dates = part[DATE_COL].sort_values()
        gaps = dates.diff().dropna()
        if not (gaps == pd.Timedelta(days=1)).all():
            raise ValueError(
                f"Non-consecutive dates found in scenario {scenario}; "
                "next-day targets cannot be formed safely."
            )

    # Numeric conversion is explicit; nonnumeric values become missing and are
    # handled by the train-fitted imputation pipeline.
    for col in WEATHER_FEATURES + [IRRIGATION_FEATURE]:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    if df[TARGET_SOURCE].isna().any():
        raise ValueError("Target column contains missing labels.")

    return df


def create_objectives(df: pd.DataFrame):
    data = df.copy().sort_values([SCENARIO_COL, DATE_COL]).reset_index(drop=True)

    # Current-day task: same-day inputs -> same-day simulated target.
    data["target_current"] = data[TARGET_SOURCE]
    data["target_date_current"] = data[DATE_COL]

    # Next-day task: shift only within a scenario. All features remain from day t.
    grouped = data.groupby(SCENARIO_COL, sort=False)
    data["target_next_day"] = grouped[TARGET_SOURCE].shift(-1)
    data["target_date_next"] = grouped[DATE_COL].shift(-1)

    valid_next = data["target_date_next"].notna()
    delta = data.loc[valid_next, "target_date_next"] - data.loc[valid_next, DATE_COL]
    if not (delta == pd.Timedelta(days=1)).all():
        raise ValueError("Next-day target alignment failed.")

    current = data.dropna(
        subset=WEATHER_FEATURES + ["target_current", "target_date_current"]
    ).copy()
    next_day = data.dropna(
        subset=WEATHER_FEATURES + ["target_next_day", "target_date_next"]
    ).copy()

    return {
        "current_day": (current, "target_current", "target_date_current"),
        "next_day": (next_day, "target_next_day", "target_date_next"),
    }


def grouped_random_split(data: pd.DataFrame, date_col: str):
    """Exploratory 70/15/15 split; every row for a target date stays together."""
    data = data.reset_index(drop=True)
    first = GroupShuffleSplit(n_splits=1, test_size=0.30, random_state=SEED)
    train_idx, temp_idx = next(
        first.split(data, groups=data[date_col])
    )
    train = data.iloc[train_idx].copy()
    temp = data.iloc[temp_idx].copy()

    second = GroupShuffleSplit(n_splits=1, test_size=0.50, random_state=SEED)
    val_idx, test_idx = next(
        second.split(temp, groups=temp[date_col])
    )
    val = temp.iloc[val_idx].copy()
    test = temp.iloc[test_idx].copy()
    return train, val, test


def chronological_split(data: pd.DataFrame, date_col: str):
    """70/15/15 split over sorted unique target dates."""
    data = data.sort_values(date_col).copy()
    dates = np.sort(data[date_col].dropna().unique())
    train_end = int(len(dates) * 0.70)
    val_end = int(len(dates) * 0.85)
    train_dates = set(dates[:train_end])
    val_dates = set(dates[train_end:val_end])
    test_dates = set(dates[val_end:])
    return (
        data[data[date_col].isin(train_dates)].copy(),
        data[data[date_col].isin(val_dates)].copy(),
        data[data[date_col].isin(test_dates)].copy(),
    )


def validate_splits(splits, date_col: str, scenario_col: str):
    date_sets = [set(part[date_col].unique()) for part in splits]
    for i in range(3):
        for j in range(i + 1, 3):
            if date_sets[i].intersection(date_sets[j]):
                raise AssertionError("Target-date overlap across data partitions.")

    for part in splits:
        if not part.empty:
            counts = part.groupby(date_col)[scenario_col].nunique()
            if not (counts == 2).all():
                raise AssertionError("A partition contains an incomplete scenario pair.")


def make_preprocessor(numeric_features, categorical_features, scale_numeric):
    numeric_steps = [("imputer", SimpleImputer(strategy="median"))]
    if scale_numeric:
        numeric_steps.append(("scaler", StandardScaler()))
    numeric_pipe = Pipeline(numeric_steps)

    transformers = [("numeric", numeric_pipe, numeric_features)]
    if categorical_features:
        categorical_pipe = Pipeline([
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore")),
        ])
        transformers.append(("categorical", categorical_pipe, categorical_features))

    return ColumnTransformer(transformers=transformers, remainder="drop")


def model_zoo(numeric_features, categorical_features):
    def build(estimator, scale=False):
        prep = make_preprocessor(numeric_features, categorical_features, scale)
        return Pipeline([("preprocess", prep), ("model", estimator)])

    return {
        "Dummy_MostFrequent": build(
            DummyClassifier(strategy="most_frequent")
        ),
        "LogisticRegression": build(
            LogisticRegression(
                max_iter=3000,
                class_weight="balanced",
                random_state=SEED,
            ),
            scale=True,
        ),
        "DecisionTree": build(
            DecisionTreeClassifier(
                class_weight="balanced",
                min_samples_leaf=5,
                random_state=SEED,
            )
        ),
        "RandomForest": build(
            RandomForestClassifier(
                n_estimators=400,
                class_weight="balanced",
                min_samples_leaf=2,
                max_features="sqrt",
                n_jobs=-1,
                random_state=SEED,
            )
        ),
        "ExtraTrees": build(
            ExtraTreesClassifier(
                n_estimators=400,
                class_weight="balanced",
                min_samples_leaf=2,
                max_features="sqrt",
                n_jobs=-1,
                random_state=SEED,
            )
        ),
        "SVM_RBF": build(
            SVC(
                kernel="rbf",
                C=1.0,
                class_weight="balanced",
                probability=True,
                random_state=SEED,
            ),
            scale=True,
        ),
        "GradientBoosting": build(
            GradientBoostingClassifier(random_state=SEED)
        ),
    }


def calculate_metrics(y_true, y_pred):
    return {
        "n": int(len(y_true)),
        "accuracy": accuracy_score(y_true, y_pred),
        "balanced_accuracy": balanced_accuracy_score(y_true, y_pred),
        "macro_precision": precision_score(
            y_true, y_pred, labels=CLASSES, average="macro", zero_division=0
        ),
        "macro_recall": recall_score(
            y_true, y_pred, labels=CLASSES, average="macro", zero_division=0
        ),
        "macro_f1": f1_score(
            y_true, y_pred, labels=CLASSES, average="macro", zero_division=0
        ),
        "weighted_f1": f1_score(
            y_true, y_pred, average="weighted", zero_division=0
        ),
    }


def class_coverage(y, split_name):
    present = set(pd.Series(y).dropna().unique())
    return {
        "split": split_name,
        "present_classes": "|".join(c for c in CLASSES if c in present),
        "missing_classes": "|".join(c for c in CLASSES if c not in present),
    }


def save_confusion(y_true, y_pred, path: Path, title: str):
    cm = confusion_matrix(y_true, y_pred, labels=CLASSES)
    fig, ax = plt.subplots(figsize=(6.5, 5.5))
    ConfusionMatrixDisplay(cm, display_labels=CLASSES).plot(
        ax=ax, cmap="Blues", colorbar=False, values_format="d"
    )
    ax.set_title(title)
    fig.tight_layout()
    fig.savefig(path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def save_class_distribution(splits, target_col, path: Path, title: str):
    counts = pd.DataFrame({
        name: part[target_col].value_counts().reindex(CLASSES, fill_value=0)
        for name, part in zip(["train", "validation", "test"], splits)
    }).T
    counts.to_csv(path.with_suffix(".csv"))
    ax = counts.plot(kind="bar", figsize=(8.5, 5))
    ax.set_title(title)
    ax.set_xlabel("Partition")
    ax.set_ylabel("Records")
    ax.grid(axis="y", alpha=0.25)
    plt.xticks(rotation=0)
    plt.tight_layout()
    plt.savefig(path, dpi=300, bbox_inches="tight")
    plt.close()


def run_random_benchmark(objective, data, target_col, date_col, dirs, repeats):
    splits = grouped_random_split(data, date_col)
    train, val, test = splits
    validate_splits(splits, date_col, SCENARIO_COL)

    split_rows = []
    for name, part in zip(["train", "validation", "test"], splits):
        row = class_coverage(part[target_col], name)
        row.update({
            "objective": objective,
            "records": len(part),
            "unique_target_dates": part[date_col].nunique(),
            "min_target_date": str(part[date_col].min().date()),
            "max_target_date": str(part[date_col].max().date()),
            "class_counts": json.dumps(
                part[target_col].value_counts().reindex(CLASSES, fill_value=0).to_dict()
            ),
        })
        split_rows.append(row)

    pd.DataFrame(split_rows).to_csv(
        dirs["tables"] / f"{objective}_random_split_diagnostics.csv",
        index=False,
    )
    save_class_distribution(
        splits, target_col,
        dirs["figures"] / f"{objective}_random_class_distribution.png",
        f"{objective}: date-grouped random class distribution",
    )

    results = []
    selected_models = []

    for group_name, spec in FEATURE_GROUPS.items():
        numeric = spec["numeric"]
        categorical = spec["categorical"]
        features = numeric + categorical

        candidates = []
        for model_name, estimator in model_zoo(numeric, categorical).items():
            fitted = clone(estimator)
            fitted.fit(train[features], train[target_col])
            val_pred = fitted.predict(val[features])
            val_metrics = calculate_metrics(val[target_col], val_pred)
            row = {
                "objective": objective,
                "evaluation_track": "date_grouped_random_exploratory",
                "feature_group": group_name,
                "model": model_name,
                "features": "|".join(features),
                "validation_present_classes": "|".join(
                    c for c in CLASSES if c in set(val[target_col])
                ),
                "validation_missing_classes": "|".join(
                    c for c in CLASSES if c not in set(val[target_col])
                ),
                "validation_macro_f1": val_metrics["macro_f1"],
                "validation_balanced_accuracy": val_metrics["balanced_accuracy"],
                "validation_weighted_f1": val_metrics["weighted_f1"],
            }
            results.append(row)
            candidates.append((model_name, estimator, val_metrics["macro_f1"],
                               val_metrics["balanced_accuracy"]))

        # Deterministic tie-break: validation macro-F1, then balanced accuracy.
        best_name, best_estimator, best_f1, best_bal_acc = max(
            candidates, key=lambda item: (item[2], item[3])
        )

        # Refit selected model on train + validation, then evaluate test once.
        train_val = pd.concat([train, val], axis=0).sort_values(date_col)
        final_model = clone(best_estimator)
        final_model.fit(train_val[features], train_val[target_col])
        test_pred = final_model.predict(test[features])
        test_metrics = calculate_metrics(test[target_col], test_pred)

        selected_row = {
            "objective": objective,
            "evaluation_track": "date_grouped_random_exploratory",
            "feature_group": group_name,
            "selected_model": best_name,
            "selection_metric": "validation_macro_f1",
            "validation_macro_f1": best_f1,
            "validation_balanced_accuracy": best_bal_acc,
            "test_present_classes": "|".join(
                c for c in CLASSES if c in set(test[target_col])
            ),
            "test_missing_classes": "|".join(
                c for c in CLASSES if c not in set(test[target_col])
            ),
        }
        selected_row.update({"test_" + k: v for k, v in test_metrics.items()})
        selected_models.append(selected_row)

        prefix = f"{objective}_random_{group_name}_{best_name}"
        save_confusion(
            test[target_col], test_pred,
            dirs["figures"] / f"{prefix}_test_confusion_matrix.png",
            f"{prefix}: held-out test",
        )
        report = classification_report(
            test[target_col], test_pred,
            labels=CLASSES, output_dict=True, zero_division=0,
        )
        pd.DataFrame(report).T.to_csv(
            dirs["reports"] / f"{prefix}_test_classification_report.csv"
        )

        model_path = dirs["models"] / f"{prefix}.joblib"
        joblib.dump({
            "model": final_model,
            "model_name": best_name,
            "features": features,
            "numeric_features": numeric,
            "categorical_features": categorical,
            "classes": CLASSES,
            "objective": objective,
            "feature_group": group_name,
            "evaluation_track": "date_grouped_random_exploratory",
            "selection_metric": "validation_macro_f1",
            "validation_macro_f1": best_f1,
            "random_state": SEED,
            "note": (
                "Target is simulated/rule-derived. Next-day intervention feature, "
                "if present, is the day-t quantity and must be known at prediction time."
            ),
        }, model_path)

        # Permutation importance is computed only for the selected model.
        # With correlated weather variables, interpret rankings as exploratory.
        if repeats > 0:
            try:
                perm = permutation_importance(
                    final_model,
                    test[features],
                    test[target_col],
                    scoring="f1_macro",
                    n_repeats=repeats,
                    random_state=SEED,
                    n_jobs=-1,
                )
                importance = pd.DataFrame({
                    "feature": features,
                    "importance_mean": perm.importances_mean,
                    "importance_std": perm.importances_std,
                }).sort_values("importance_mean", ascending=False)
                importance.to_csv(
                    dirs["tables"] / f"{prefix}_permutation_importance.csv",
                    index=False,
                )
                top = importance.head(15).sort_values("importance_mean")
                fig, ax = plt.subplots(figsize=(9, 6.5))
                ax.barh(top["feature"], top["importance_mean"],
                        xerr=top["importance_std"])
                ax.set_xlabel("Decrease in test macro-F1 after permutation")
                ax.set_title(f"{prefix}: exploratory permutation importance")
                ax.grid(axis="x", alpha=0.25)
                fig.tight_layout()
                fig.savefig(
                    dirs["figures"] / f"{prefix}_permutation_importance.png",
                    dpi=300, bbox_inches="tight",
                )
                plt.close(fig)
            except Exception as exc:
                (dirs["reports"] / f"{prefix}_permutation_importance_warning.txt").write_text(
                    f"Permutation importance could not be calculated: {exc}\n"
                )

    pd.DataFrame(results).to_csv(
        dirs["tables"] / f"{objective}_random_validation_model_comparison.csv",
        index=False,
    )
    pd.DataFrame(selected_models).to_csv(
        dirs["tables"] / f"{objective}_random_selected_test_results.csv",
        index=False,
    )
    return results, selected_models


def run_chronological_diagnostic(objective, data, target_col, date_col, dirs):
    """
    Temporal diagnostic only. Does not select a model using validation.
    Random Forest is a predeclared reference model; Dummy is a baseline.
    """
    splits = chronological_split(data, date_col)
    train, val, test = splits
    validate_splits(splits, date_col, SCENARIO_COL)

    save_class_distribution(
        splits, target_col,
        dirs["figures"] / f"{objective}_chronological_class_distribution.png",
        f"{objective}: chronological class distribution",
    )

    rows = []
    coverage = []
    for name, part in zip(["train", "validation", "test"], splits):
        coverage.append({
            "objective": objective,
            **class_coverage(part[target_col], name),
            "records": len(part),
            "unique_target_dates": part[date_col].nunique(),
            "min_target_date": str(part[date_col].min().date()),
            "max_target_date": str(part[date_col].max().date()),
            "class_counts": json.dumps(
                part[target_col].value_counts().reindex(CLASSES, fill_value=0).to_dict()
            ),
        })
    pd.DataFrame(coverage).to_csv(
        dirs["tables"] / f"{objective}_chronological_split_diagnostics.csv",
        index=False,
    )

    # Use the weather baseline feature group for a transparent temporal reference.
    features = FEATURE_GROUPS["weather_baseline"]["numeric"]
    for model_name, estimator in {
        "Dummy_MostFrequent": model_zoo(features, [])["Dummy_MostFrequent"],
        "RandomForest": model_zoo(features, [])["RandomForest"],
    }.items():
        fitted = clone(estimator)
        fitted.fit(train[features], train[target_col])
        for split_name, part in [("validation", val), ("test", test)]:
            pred = fitted.predict(part[features])
            row = {
                "objective": objective,
                "evaluation_track": "chronological_diagnostic_only",
                "feature_group": "weather_baseline",
                "model": model_name,
                "split": split_name,
                "present_classes": "|".join(
                    c for c in CLASSES if c in set(part[target_col])
                ),
                "missing_classes": "|".join(
                    c for c in CLASSES if c not in set(part[target_col])
                ),
            }
            row.update(calculate_metrics(part[target_col], pred))
            rows.append(row)
            if split_name == "test":
                prefix = f"{objective}_chronological_{model_name}"
                save_confusion(
                    part[target_col], pred,
                    dirs["figures"] / f"{prefix}_test_confusion_matrix.png",
                    f"{prefix}: chronological test diagnostic",
                )
    result = pd.DataFrame(rows)
    result.to_csv(
        dirs["tables"] / f"{objective}_chronological_diagnostic_metrics.csv",
        index=False,
    )
    return rows


