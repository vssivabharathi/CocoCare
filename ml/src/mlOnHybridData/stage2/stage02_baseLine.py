#!/usr/bin/env python3
"""
CocoCare Stage 2 — baseline ML experiments
==========================================

Implements the three feature groups defined in stage02_ml.ipynb for:
  1. Current-day classification: inputs on day t -> rule-derived label on day t
  2. Next-day prediction: inputs through day t -> rule-derived label on day t+1

Evaluation:
  A. Date-grouped random benchmark (exploratory; not a temporal forecast test)
     - 70% train / 15% validation / 15% test by target date.
     - Model selection uses validation macro-F1 only.
     - The selected model is refit on train + validation and evaluated once on test.
  B. Chronological diagnostic
     - 70% earliest dates / 15% next dates / 15% latest dates.
     - Random-forest diagnostic is reported, but no model is selected from this
       split because the validation period may omit one or more classes.

IMPORTANT RESEARCH LIMITATION:
The target water_stress_rule_derived is generated by the Stage 2 water-balance
simulation. These experiments measure how well ML models reproduce those
simulated labels. They do NOT establish field-validated coconut water-stress
prediction or irrigation efficacy.

For next-day prediction, all features come from day t. In the intervention-aware
group, irrigation_litres_per_palm_simulated therefore means the irrigation
quantity recorded for day t, not a future day t+1 quantity. This feature is
appropriate only if that day-t quantity is known at prediction time.

Run from the CocoCare repository root:
  python ml/src/mlOnHybridData/stage2/stage2_baseline_ml.py

Or provide explicit paths:
  python stage2_baseline_ml.py --data /path/to/stage2_combined_scenarios.csv \
      --output /path/to/stage2_ml_baseline
"""

